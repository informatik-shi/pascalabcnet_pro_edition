param(
    [Parameter(Mandatory=$true)][string]$UnicodeData,
    [string]$Output = "$PSScriptRoot/../src/unicode.hpp"
)
$ErrorActionPreference = 'Stop'
# Development tool only. Normal builds use the checked-in C++ tables.
# https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt
$expected = '2FC713E6A31A87C4850A37FE2CAFFA4218180FADB5DE86B43A143DDB4581FB86'
if ((Get-FileHash -LiteralPath $UnicodeData -Algorithm SHA256).Hash -ne $expected) {
    throw 'Expected the unmodified Unicode 15.1.0 UnicodeData.txt'
}
$letters = [bool[]]::new(65536)
$properties = [int[]]::new(65536)
$lower = [System.Collections.Generic.List[string]]::new()
$upper = [System.Collections.Generic.List[string]]::new()
$first = -1
foreach ($line in [System.IO.File]::ReadLines((Resolve-Path $UnicodeData))) {
    $fields = $line.Split(';')
    $code = [Convert]::ToInt32($fields[0],16)
    if ($fields[1].EndsWith(', First>')) { $first = $code; continue }
    if ($code -le 65535 -and $fields[2].StartsWith('L')) {
        $start = if ($first -ge 0) { $first } else { $code }
        for ($point=$start; $point -le $code; ++$point) { $letters[$point] = $true }
    }
    if ($code -le 65535) {
        $properties[$code] = switch ($fields[2]) { 'Lu' { 1 } 'Ll' { 2 } 'Nd' { 4 } default { 0 } }
    }
    $first = -1
    if ($fields[13]) { $lower.Add(('    {{0x{0:X4},0x{1:X4}}},' -f $code,[Convert]::ToInt32($fields[13],16))) }
    if ($fields[12]) { $upper.Add(('    {{0x{0:X4},0x{1:X4}}},' -f $code,[Convert]::ToInt32($fields[12],16))) }
}
$ranges = [System.Collections.Generic.List[string]]::new()
$propertyRanges = [System.Collections.Generic.List[string]]::new()
for ($point=0; $point -le 65535; ++$point) {
    if (!$properties[$point]) { continue }
    $start = $point; $bits = $properties[$point]
    while ($point -lt 65535 -and $properties[$point+1] -eq $bits) { ++$point }
    $propertyRanges.Add(('    {{0x{0:X4},0x{1:X4},{2}}},' -f $start,$point,$bits))
}
for ($point=0; $point -le 65535; ++$point) {
    if (!$letters[$point]) { continue }
    $start = $point
    while ($point -lt 65535 -and $letters[$point+1]) { ++$point }
    $ranges.Add(('    {{0x{0:X4},0x{1:X4}}},' -f $start,$point))
}
$text = [System.Collections.Generic.List[string]]::new()
$text.AddRange([string[]]@(
    '// Generated by scripts/generate-unicode.ps1 from Unicode 15.1.0.',
    '// Source: https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt',
    '// SHA-256: 2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86',
    '// Distributed under licenses/Unicode-License.txt.',
    '#pragma once', '#include <algorithm>', '#include <array>', '',
    'namespace abc::unicode {',
    'struct Range { char16_t first, last; };',
    'struct Mapping { char32_t from, to; };',
    'struct PropertyRange { char16_t first, last; unsigned bits; };',
    "inline constexpr std::array<Range,$($ranges.Count)> letters{{"
))
$text.AddRange($ranges); $text.Add('}};')
$text.Add("inline constexpr std::array<PropertyRange,$($propertyRanges.Count)> properties{{")
$text.AddRange($propertyRanges); $text.Add('}};')
$text.Add("inline constexpr std::array<Mapping,$($lower.Count)> lowercase{{")
$text.AddRange($lower); $text.Add('}};')
$text.Add("inline constexpr std::array<Mapping,$($upper.Count)> uppercase{{")
$text.AddRange($upper); $text.Add('}};')
$text.AddRange([string[]]@(
    'inline bool is_letter(char16_t value) {',
    '    const auto found=std::lower_bound(letters.begin(),letters.end(),value,[](const Range& range,char16_t c) { return range.last<c; });',
    '    return found!=letters.end() && found->first<=value;',
    '}',
    'inline unsigned category_bits(char16_t value) {',
    '    const auto found=std::lower_bound(properties.begin(),properties.end(),value,[](const PropertyRange& range,char16_t c) { return range.last<c; });',
    '    return found!=properties.end() && found->first<=value ? found->bits : 0;',
    '}',
    'template<std::size_t N> inline char32_t mapped(char32_t value,const std::array<Mapping,N>& table) {',
    '    const auto found=std::lower_bound(table.begin(),table.end(),value,[](const Mapping& mapping,char32_t c) { return mapping.from<c; });',
    '    return found!=table.end() && found->from==value ? found->to : value;',
    '}',
    'inline char32_t to_lower(char32_t value) { return mapped(value,lowercase); }',
    'inline char32_t to_upper(char32_t value) { return mapped(value,uppercase); }',
    '} // namespace abc::unicode', ''
))
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Output),($text -join "`n"),[System.Text.UTF8Encoding]::new($false))
Write-Output "Generated tables: $($ranges.Count) BMP letter ranges, $($propertyRanges.Count) BMP property ranges, $($lower.Count) scalar lowercase mappings, $($upper.Count) scalar uppercase mappings"
