const output=path.join(root,'src/sbcs_data.inc');
if(process.argv.includes('--check')){if(fs.readFileSync(output,'utf8').replaceAll('\r\n','\n')!==result)throw Error('Generated codec data is stale');}
else fs.writeFileSync(output,result);
console.log(JSON.stringify({codecs:count,aliases:aliases.length,sparse_entries:sparse,generated_bytes:Buffer.byteLength(result)}));
