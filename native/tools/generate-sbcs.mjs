const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const data=fs.readFileSync(path.join(root,'tests/fixtures/sbcs-reference.bin'));let offset=0;
const bytes=n=>{if(offset+n>data.length)throw Error('Truncated reference');const result=data.subarray(offset,offset+n);offset+=n;return result;};
const integer=()=>bytes(4).readInt32LE();
const string=()=>{let n=0,shift=0,b;do{b=bytes(1)[0];n|=(b&127)<<shift;shift+=7;if(shift>28)throw Error('Invalid string length');}while(b&128);return bytes(n).toString('utf8');};
if(bytes(8).toString()!=='ABCSBCS2')throw Error('Invalid reference header');const count=integer(),codecs=[];
const hex=n=>'0x'+n.toString(16);
const lines=(values,size=12)=>Array.from({length:Math.ceil(values.length/size)},(_,i)=>'    '+values.slice(i*size,(i+1)*size).join(',')+',').join('\n');
let result='// Generated by native/tools/generate-sbcs.mjs from the Framework reference.\n// No runtime framework, platform codec or generated-code dependency.\n';
let sparse=0;
for(let i=0;i<count;++i){
 const code=integer(),name=string(),runtime=string(),fallback=bytes(1)[0],holdHigh=bytes(1)[0],decoded=bytes(512),decodeStrict=bytes(32),encoded=bytes(65536),encodeStrict=bytes(8192),entries=[];
 for(let c=0;c<65536;++c){const exact=(encodeStrict[c>>3]>>(c&7))&1;if(exact||encoded[c]!==fallback)entries.push((c*65536)+(exact?256:0)+encoded[c]);}
 const prefix='sbcs_'+code;
 result+=`constexpr char16_t ${prefix}_decode[]={\n${lines(Array.from({length:256},(_,i)=>hex(decoded.readUInt16LE(i*2))))}\n};\n`;
 result+=`constexpr std::uint8_t ${prefix}_strict[]={\n${lines([...decodeStrict].map(hex))}\n};\n`;
 result+=`constexpr std::uint32_t ${prefix}_encode[]={\n${lines(entries.map(n=>hex(n)+'U'),8)}\n};\n`;
 codecs.push({code,name,runtime,fallback,holdHigh,prefix});sparse+=entries.length;
}
if(offset!==data.length||count!==95)throw Error('Unexpected reference size/count');
result+='constexpr SingleByteCodec sbcs_codecs[]={\n'+codecs.map(c=>`    {${c.code},${c.fallback},${!!c.holdHigh},${c.prefix}_decode,${c.prefix}_strict,${c.prefix}_encode},`).join('\n')+'\n};\n';
const supported=new Set([...codecs.map(c=>c.code),65001,1200,1201,12000,12001]);
